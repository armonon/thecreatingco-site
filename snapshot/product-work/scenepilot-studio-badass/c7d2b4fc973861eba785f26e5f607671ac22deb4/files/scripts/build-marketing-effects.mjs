import { build } from "esbuild";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { createHash } from "node:crypto";
import { mkdtemp, mkdir, readFile, writeFile, unlink } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import electron from "electron";
const run = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const workspace = await mkdtemp(path.join(os.tmpdir(), "scenepilot-gallery-"));
const bundle = path.join(workspace, "render.js"), result = path.join(workspace, "result.json"), payload = path.join(workspace, "payload.json");
const source = path.join(root, "site/assets/alpine-source-20260911.jpg");
await build({ entryPoints: [path.join(root, "scripts/render-marketing-effects.ts")], outfile: bundle, bundle: true, platform: "browser", format: "iife", globalName: "ScenePilotGalleryRender" });
await writeFile(payload, JSON.stringify({ source, bundle, result }));
const rendering = run(electron, [path.join(root, "scripts/render-marketing-effects-electron.mjs"), payload], { timeout: 610_000, maxBuffer: 2_000_000 });
rendering.child.stdout.on("data", chunk => process.stdout.write(chunk));
await rendering;
const { files, gallery } = JSON.parse(await readFile(result, "utf8"));
const output = path.join(root, "site/assets/effects-gallery"); await mkdir(output, { recursive: true });
let previous = {};
try { previous = JSON.parse(await readFile(path.join(output, "provenance.json"), "utf8")).hashes ?? {}; } catch { /* first generation */ }
const hashes = {};
const canonical = new Map(), aliases = new Map();
for (const [name, data] of Object.entries(files)) {
  if (!/^[a-z0-9-]+\.jpg$/.test(name) || !data.startsWith("data:image/jpeg;base64,")) throw new Error("Invalid rendered gallery asset");
  const bytes = Buffer.from(data.split(",")[1], "base64");
  const hash = createHash("sha256").update(bytes).digest("hex");
  if (canonical.has(hash)) { aliases.set(`assets/effects-gallery/${name}`, `assets/effects-gallery/${canonical.get(hash)}`); continue; }
  canonical.set(hash, name); hashes[name] = hash;
  await writeFile(path.join(output, name), bytes);
}
// Identical original/frame samples share a URL and browser cache entry.
const deduplicate = value => typeof value === "string" ? aliases.get(value) ?? value : Array.isArray(value) ? value.map(deduplicate) : value && typeof value === "object" ? Object.fromEntries(Object.entries(value).map(([key, item]) => [key, deduplicate(item)])) : value;
const manifest = deduplicate(gallery);
const { stdout: revision } = await run("git", ["rev-parse", "HEAD"], { cwd: root });
const sourceFiles = ["scripts/build-marketing-effects.mjs", "scripts/marketing-effect-catalog.ts", "scripts/render-marketing-effects.ts", "lib/compositor.ts", "lib/clip-effects.ts", "lib/grade.ts", "lib/transitions.ts", "lib/strobe.ts", "lib/motion.ts", "lib/stutter.ts", "lib/speed.ts", "lib/text-animate.ts"];
const rendererSources = Object.fromEntries(await Promise.all(sourceFiles.map(async file => [file, createHash("sha256").update(await readFile(path.join(root, file))).digest("hex")])));
const provenance = { renderer: "ScenePilot effectPreviewPlan + paintFramePlan + computeFramePlan + createGradePass (WebGL)", revision: revision.trim(), rendererSources, renderedAt: new Date().toISOString(), entries: gallery.entries.length, width: gallery.width, height: gallery.height, sampleTime: gallery.time, source: "Johannes Mändle / Unsplash — alpine-source-20260911.jpg (see site/README.md); timing samples add a generated moving reference card", sourceSHA256: createHash("sha256").update(await readFile(source)).digest("hex"), hashes };
await writeFile(path.join(output, "provenance.json"), JSON.stringify(provenance, null, 2) + "\n");
await writeFile(path.join(output, "gallery-data.js"), `// Generated by scripts/build-marketing-effects.mjs using the real ScenePilot compositor.\nglobalThis.ScenePilotGallery = ${JSON.stringify(manifest, null, 2)};\n`);
// Remove only obsolete generated JPEGs whose bytes still match our old manifest.
for (const [name, expected] of Object.entries(previous)) {
  if (hashes[name] || !/^[a-z0-9-]+\.jpg$/.test(name)) continue;
  const target = path.join(output, name);
  try {
    if (createHash("sha256").update(await readFile(target)).digest("hex") === expected) await unlink(target);
  } catch (error) { if (error.code !== "ENOENT") throw error; }
}
console.log(`Rendered ${gallery.entries.length} entries into ${Object.keys(hashes).length} unique assets (${aliases.size} duplicate frames shared).`);
